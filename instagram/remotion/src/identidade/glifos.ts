/**
 * Largura de `texto` em fracao de em, sob `papel`.
 *
 * Caractere fora da tabela cai no avanco do `x` do mesmo papel -- nunca em 0,
 * que faria um texto largo parecer caber.
 */
export function larguraEm(texto: string, papel: Papel): number {
  const t = GLIFOS[papel];
  const padrao = t["x"];
  let soma = 0;
  for (const c of texto) soma += t[c] ?? padrao;
  return soma;
}
